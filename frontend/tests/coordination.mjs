import { signIn, openTestProject } from "./account-helper.mjs";
import { chromium } from "@playwright/test";
import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { mkdir, readFile } from "node:fs/promises";
import { resolve } from "node:path";

const output = resolve(`data/artifacts/coordination/ui-${Date.now()}`);
await mkdir(output, { recursive: true });
const fixtures = resolve(output, "fixtures");
await promisify(execFile)(resolve(".venv/Scripts/python.exe"), ["frontend/tests/make_inspection_fixtures.py", fixtures], { windowsHide: true });
const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE });
const page = await browser.newPage({ viewport: { width: 1536, height: 1100 } });
const errors = [];
let releaseModel;
const modelGate = new Promise(done => { releaseModel = done; });
await page.route("**/model.glb", async route => { await modelGate; await route.continue(); });
page.on("pageerror", error => errors.push(error.message));
try {
  await page.goto("http://127.0.0.1:1420/#inspection");
  await signIn(page);
  await page.getByText("Sẵn sàng kiểm tra", { exact: true }).waitFor();
  await openTestProject(page);
  await page.getByLabel("Chọn tệp IFC, PDF, DXF hoặc DWG").setInputFiles([resolve(fixtures, "ARCH.ifc"), resolve(fixtures, "floor.dxf")]);
  await page.getByRole("button", { name: "Bắt đầu kiểm tra", exact: true }).click();
  await page.getByText("Đã xử lý 2/2 tệp", { exact: true }).waitFor({ timeout: 60000 });
  const workspace = page.getByRole("region", { name: "Phối hợp bản vẽ và mô hình" });
  await workspace.getByLabel("Hiển thị ARCH.ifc", { exact: true }).uncheck();
  releaseModel();
  await workspace.getByText("Đã hiển thị 1/1 mô hình", { exact: true }).waitFor({ timeout: 30000 });
  const hiddenImage = await workspace.locator("canvas").screenshot();
  await workspace.getByLabel("Hiển thị ARCH.ifc", { exact: true }).check();
  assert.notDeepEqual(await workspace.locator("canvas").screenshot(), hiddenImage);
  const cad = workspace.getByRole("img", { name: "Bản vẽ DXF của bạn" });
  await cad.waitFor();
  await cad.locator("path").first().waitFor({ state: "attached" });
  const visibleBefore = await cad.locator('path[data-layer="A-WALL"]').count();
  assert.ok(visibleBefore > 0);
  await workspace.getByLabel("Layer A-WALL", { exact: true }).uncheck();
  assert.equal(await cad.locator('path[data-layer="A-WALL"]').count(), 0);
  await workspace.getByLabel("Layer A-WALL", { exact: true }).check();
  const before = await cad.getAttribute("viewBox");
  await workspace.getByRole("button", { name: "Phóng to bản vẽ", exact: true }).click();
  assert.notEqual(await cad.getAttribute("viewBox"), before);
  await workspace.getByRole("button", { name: "Vừa bản vẽ", exact: true }).click();
  const select = workspace.getByLabel("Chọn cấu kiện IFC", { exact: true });
  await select.selectOption({ index: 1 });
  await workspace.getByTestId("ifc-selection").getByText("Synthetic wall", { exact: true }).waitFor();
  const canvas = workspace.locator("canvas");
  const imageBefore = await canvas.screenshot();
  await workspace.getByRole("button", { name: "Xoay mô hình", exact: true }).click();
  assert.notDeepEqual(await canvas.screenshot(), imageBefore);
  await workspace.getByLabel("Tên dự án phối hợp").fill("Synthetic pilot");
  await workspace.getByRole("button", { name: "So trục XY", exact: true }).click();
  await workspace.getByText("Khớp 2/2 trục XY", { exact: true }).waitFor();
  assert.equal(await workspace.getByRole("button", { name: "Xác nhận và lưu liên kết", exact: true }).isDisabled(), true);
  await workspace.getByLabel("Tôi xác nhận bản vẽ và mô hình cùng công trình và đúng tầng").check();
  await workspace.getByRole("button", { name: "Xác nhận và lưu liên kết", exact: true }).click();
  await workspace.getByText("Đã lưu liên kết tầng", { exact: true }).waitFor();
  const downloadPromise = page.waitForEvent("download");
  await workspace.getByRole("button", { name: "Tải liên kết JSON", exact: true }).click();
  const download = await downloadPromise;
  const link = JSON.parse(await readFile(await download.path(), "utf8"));
  assert.equal(link.confirmed, true);
  assert.equal(link.clash_detection, "not_run");
  await workspace.getByLabel("Dịch X (m)", { exact: true }).fill("1");
  assert.equal(await workspace.getByText("Đã lưu liên kết tầng", { exact: true }).count(), 0);
  await workspace.getByRole("button", { name: "So trục XY", exact: true }).click();
  await workspace.getByText("Chưa đủ cơ sở xác nhận căn khớp", { exact: true }).waitFor();
  assert.equal(await workspace.getByRole("button", { name: "Xác nhận và lưu liên kết", exact: true }).isDisabled(), true);
  await page.screenshot({ path: resolve(output, "desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 375, height: 812 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: resolve(output, "mobile.png"), fullPage: true });
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ status: "passed", output, checks: "DXF layers/zoom, IFC GUID selection/rotation, preview, explicit confirmation, persisted link download, invalidation, offset rejection, mobile, console" }));
} finally { releaseModel(); await browser.close(); }
